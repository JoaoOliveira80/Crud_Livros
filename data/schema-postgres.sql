-- PostgreSQL 17 — optional explicit initial schema for production-style setup.
-- Run on a fresh database BEFORE starting the API with DDL_AUTO=validate.
-- The application is configured with ddl-auto=update in dev for convenience.
CREATE TABLE IF NOT EXISTS livros (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  titulo VARCHAR(180) NOT NULL,
  autor VARCHAR(120) NOT NULL,
  genero VARCHAR(80) NOT NULL,
  ano INTEGER NOT NULL CHECK (ano BETWEEN 1000 AND 2100),
  descricao VARCHAR(2000),
  status VARCHAR(24) NOT NULL DEFAULT 'QUERO_LER' CHECK (status IN ('QUERO_LER','LENDO','LIDO')),
  avaliacao INTEGER CHECK (avaliacao BETWEEN 0 AND 5),
  paginas INTEGER CHECK (paginas > 0),
  pagina_atual INTEGER DEFAULT 0 CHECK (pagina_atual >= 0),
  favorito BOOLEAN NOT NULL DEFAULT FALSE,
  notas VARCHAR(3000),
  isbn VARCHAR(20),
  created_at TIMESTAMP,
  updated_at TIMESTAMP,
  CONSTRAINT ck_progresso CHECK (paginas IS NULL OR pagina_atual IS NULL OR pagina_atual <= paginas)
);
CREATE INDEX IF NOT EXISTS idx_livros_status ON livros(status);
CREATE INDEX IF NOT EXISTS idx_livros_genero ON livros(genero);
